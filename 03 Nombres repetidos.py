def hacer_suma(num1,num2):
   resultado = num1 + num2
   return resultado

def hacer_resta(num1,num2):
   resultado = num1 - num2
   return resultado

def hacer_multiplicacion(num1,num2):
   resultado = num1 * num2
   return resultado

print("La suma es:", hacer_suma(2,2))
print("La resta es de:", hacer_resta(10,5))
print("La multiplicacion es de:", hacer_multiplicacion(3,2))

